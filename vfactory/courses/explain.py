def apply(course):
    """把表里的解析写进课程（就地修改）：每道作答题有对应的解析就写 explain。返回写了几道。"""
    n = 0
    for ch in course.get('chapters') or []:
        for l in ch.get('lessons') or []:
            for r in l.get('rules') or []:
                t = EXPLAIN.get((course.get('id'), l.get('id'), r.get('key')))
                if t and r.get('kind') == 'answer':
                    r['explain'] = t
                    n += 1
    return n


def main():
    """把解析写进现有的课程 JSON（保持原来的格式），不重新生成课程和工厂。"""
    here = os.path.dirname(os.path.abspath(__file__))
    total = 0
    for cid in sorted({k[0] for k in EXPLAIN}):
        p = os.path.join(here, f'{cid}.json')
        with open(p, encoding='utf-8') as f:
            raw = f.read()
        c = json.loads(raw)
        n = apply(c)
        out = json.dumps(c, ensure_ascii=False, indent=1) + ('\n' if raw.endswith('\n') else '')
        if out != raw:
            with open(p, 'w', encoding='utf-8', newline='') as f:
                f.write(out)
        total += n
        print(_tr('{cid}: {n} 道题有解析', cid=cid, n=n))
    print(_tr('共 {total} 道', total=total))


if __name__ == '__main__':
    main()
