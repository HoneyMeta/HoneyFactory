    m.b('M1', 'processor', '1#冲压', (11, 6), time=t1, run_kw=12, idle_kw=2)
    m.b('B1', 'buffer', '缓存 1', (17, 6.5), (2.5, 2.5), capacity=cap)
    m.b('M2', 'processor', '2#焊接', (21, 6), time=t2, run_kw=15, idle_kw=2)
