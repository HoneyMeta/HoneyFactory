# ================================================================ 工厂与设备认知
def teach_line(name, speed=SPEED_SLOW, m2_defect='0.08'):
    """认知课的教学线：来料 → 毛坯缓存 → 车床 → 缓存 → 加工中心 → 输送线 → 检测 →（合格）成品仓库 /（不合格）废品箱。
    节拍都是固定值、来料比任何一台都慢，零件不排队：一件从来料到入库约 3.5 分钟。"""
    m = M(name, '法兰盘', (58, 18), [('收货区', (0, 10)), ('机加区', (10, 34)), ('检测区', (34, 46)), ('仓储区', (46, 58))], speed=speed)
    m.b('SRC', 'source', '毛坯来料', (2, 6), (4, 4), interval='90')
    m.b('B0', 'buffer', '毛坯缓存', (7.5, 6.5), (2.5, 2.5), capacity=20)
    m.b('M1', 'processor', '1#数控车床', (11, 6), time='40', run_kw=10, idle_kw=2)
    m.b('B1', 'buffer', '车铣之间缓存', (17, 6.5), (2.5, 2.5), capacity=5)
    m.b('M2', 'processor', '2#加工中心', (21, 6), time='50', run_kw=14, idle_kw=2, defects=[{'name': '尺寸超差', 'prob': m2_defect}])
    m.b('CV1', 'conveyor', '输送线', (28, 7.2), (8, 1.6), length_m=8, speed_mps=0.08, pitch_m=1, run_kw=1, idle_kw=0.3)
    m.b('QC', 'inspect', '在线检测', (36, 6), (4, 4), time='20', pod_pct=100, false_pct=0)
    m.b('OUT', 'sink', '成品仓库', (49, 5.5), (5, 5))
    m.b('NG', 'sink', '废品箱', (37, 12.5), (3, 3), node=[1480, 300], scrap=True, scrap_cause='检测判废')
    for a, b in (('SRC', 'B0'), ('B0', 'M1'), ('M1', 'B1'), ('B1', 'M2'), ('M2', 'CV1'), ('CV1', 'QC'), ('QC', 'OUT')):
        m.l(a, b)
    m.l('QC', 'NG', ap='ng')
    return m


